#!/usr/bin/env python3
"""Safe, explicit source cleanup. Never reads/mutates MongoDB, RustFS or backups.
Only remove root-level Markdown copies if an identical docs/history version exists.
"""
from pathlib import Path
import argparse, hashlib, json
ROOT=Path(__file__).resolve().parent.parent
PROTECTED={'README.md','AGENTS.md'}
def digest(path): return hashlib.sha256(path.read_bytes()).hexdigest()
def candidates():
    result=[]
    history=ROOT/'docs/history'
    for file in ROOT.glob('*.md'):
        if file.name in PROTECTED: continue
        archived=history/file.name
        if archived.is_file() and digest(file)==digest(archived):
            result.append({'path':file.name,'archive':str(archived.relative_to(ROOT)),
                           'bytes':file.stat().st_size,'sha256':digest(file)})
    cache=ROOT/'tsconfig.tsbuildinfo'
    if cache.is_file() and not cache.is_symlink() and cache.stat().st_size < 10_000_000:
        result.append({'path':cache.name,'archive':'Regenerated by TypeScript; no archive required',
                       'bytes':cache.stat().st_size,'sha256':digest(cache)})
    return sorted(result,key=lambda row:row['path'])
def main():
    parser=argparse.ArgumentParser(description='Preview or clean only verified duplicate root documentation')
    group=parser.add_mutually_exclusive_group();group.add_argument('--check',action='store_true');group.add_argument('--apply',action='store_true')
    args=parser.parse_args(); items=candidates()
    before=sum(f.stat().st_size for f in ROOT.rglob('*') if f.is_file() and 'node_modules' not in f.parts and '.next' not in f.parts)
    if args.apply:
        for item in items:
            original=ROOT/item['path']; archived=ROOT/item['archive']
            if digest(original)!=item['sha256'] or (item['path']!='tsconfig.tsbuildinfo' and
                (not archived.is_file() or digest(archived)!=item['sha256'])):
                raise RuntimeError(f'Content changed, refusing removal: {item["path"]}')
            original.unlink()
    print(json.dumps({'mode':'apply' if args.apply else 'check','candidates':items,
      'candidateBytes':sum(i['bytes'] for i in items),'beforeBytes':before,
      'afterBytes':before-sum(i['bytes'] for i in items) if args.apply else before,
      'note':'Never deletes historical verification records, backups, scans, evidence or other directories.'},indent=2))
if __name__=='__main__': main()
